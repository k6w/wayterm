export type IconName = keyof typeof Icons;

/** Component type of a registry entry, for props that take an icon component (e.g. `icon: IconComponent`). */
export type IconComponent = PhosphorIcon;

export type { IconWeight };

/**
 * Provides the default weight for every icon below it (Phosphor's own context, so it also reaches glyphs rendered
 * directly from `Icons.x`). Kit components wrap their icon slot in this: "fill" for active/pressed/selected, otherwise "regular".
 */
export function IconWeightProvider({
  weight,
  children,
}: {
  weight: IconWeight;
  children: ReactNode;
}) {
  return (
    <IconContext.Provider value={{ weight }}>{children}</IconContext.Provider>
  );
}

export interface IconProps extends Omit<
  PhosphorProps,
  "size" | "ref" | "weight"
> {
  name: IconName;
  /** "sm" = ICON_SM (14), "md" = ICON_MD (16); a number is a custom pixel size. */
  size?: "sm" | "md" | number;
  /** Overrides the weight inherited from IconWeightProvider (default "regular"). */
  weight?: IconWeight;
}

export function Icon({ name, size = "md", ...rest }: IconProps) {
  const Glyph = Icons[name];
  const px = size === "sm" ? ICON_SM.size : size === "md" ? ICON_MD.size : size;
  return <Glyph size={px} {...rest} />;
}
