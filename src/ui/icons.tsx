export type IconName = keyof typeof Icons;

/** Component type of a registry entry, for props that take an icon component (e.g. `icon: IconComponent`). */
export type IconComponent = LucideIcon;

export interface IconProps extends Omit<LucideProps, "size" | "ref"> {
  name: IconName;
  /** "sm" = ICON_SM (14), "md" = ICON_MD (16); a number is a custom pixel size with the library default stroke. */
  size?: "sm" | "md" | number;
}

export function Icon({ name, size = "md", ...rest }: IconProps) {
  const Glyph = Icons[name];
  const base = size === "sm" ? ICON_SM : size === "md" ? ICON_MD : { size };
  return <Glyph {...base} {...rest} />;
}
